from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


SCORE_WEIGHTS = {
    "independent_information": 25,
    "racing_mechanism": 20,
    "outer_oos_failure_evidence": 20,
    "leakage_safety": 15,
    "minimal_falsifiability": 10,
    "acquisition_implementation_cost": 10,
}
RUN_SCORE_THRESHOLD = 75
SAFE_EXPERIMENT_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{2,63}$")


def default_root() -> Path:
    return Path(__file__).resolve().parents[2]


def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def validate_experiment_id(value: str) -> str:
    if not SAFE_EXPERIMENT_ID.fullmatch(value):
        raise ValueError(
            "experiment_id must be 3-64 characters and contain only ASCII letters, "
            "digits, '_' or '-'; it must start with a letter or digit"
        )
    return value


def score_components(args: argparse.Namespace) -> dict[str, int]:
    values = {name: int(getattr(args, name)) for name in SCORE_WEIGHTS}
    errors = [
        f"{name} must be between 0 and {SCORE_WEIGHTS[name]} (received {value})"
        for name, value in values.items()
        if not 0 <= value <= SCORE_WEIGHTS[name]
    ]
    if errors:
        raise ValueError("; ".join(errors))
    return values


def relative_display(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def render_markdown(
    template: str,
    *,
    experiment_id: str,
    title: str,
    owner: str,
    hypothesis: str,
    notes: str,
    created_at: str,
    status: str,
    scores: dict[str, int],
    total: int,
) -> str:
    replacements = {
        "{{EXPERIMENT_ID}}": experiment_id,
        "{{TITLE}}": title,
        "{{OWNER}}": owner,
        "{{HYPOTHESIS}}": hypothesis,
        "{{CREATED_AT}}": created_at,
        "{{STATUS}}": status,
        "{{SCORE_INDEPENDENT_INFORMATION}}": str(scores["independent_information"]),
        "{{SCORE_RACING_MECHANISM}}": str(scores["racing_mechanism"]),
        "{{SCORE_OUTER_OOS_FAILURE_EVIDENCE}}": str(scores["outer_oos_failure_evidence"]),
        "{{SCORE_LEAKAGE_SAFETY}}": str(scores["leakage_safety"]),
        "{{SCORE_MINIMAL_FALSIFIABILITY}}": str(scores["minimal_falsifiability"]),
        "{{SCORE_ACQUISITION_IMPLEMENTATION_COST}}": str(scores["acquisition_implementation_cost"]),
        "{{SCORE_TOTAL}}": str(total),
        "{{AUTO_EXECUTION_ELIGIBLE}}": "false",
    }
    rendered_template = template
    for marker, value in replacements.items():
        rendered_template = rendered_template.replace(marker, value)

    score_rows = "\n".join(
        f"| `{name}` | {scores[name]} | {weight} |"
        for name, weight in SCORE_WEIGHTS.items()
    )
    hypothesis_text = hypothesis or "未記入"
    notes_text = notes or "なし"
    intake = f"""<!--
Generated by scripts/research/create_experiment.py.
This intake block records the proposal as created; execution still requires a
separate human APPROVED_TO_RUN registry event.
-->

# {experiment_id}: {title}

## Level-3 intake

- Status: `{status}`
- Owner: {owner}
- Created at (UTC): `{created_at}`
- Score: **{total}/100** (run threshold: {RUN_SCORE_THRESHOLD})
- Automatic execution: **forbidden**
- Human approval to run: **not granted**
- Production approval: **false**
- Merge approval: **false**
- BUY approval: **false**
- Formal BUY: **false**
- Send order: **false**
- Stake: **0**

### Hypothesis

{hypothesis_text}

### Intake scorecard

| Dimension | Score | Maximum |
|---|---:|---:|
{score_rows}

### Intake notes

{notes_text}

---

"""
    return intake + rendered_template.rstrip() + "\n"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Create a Level-3 research proposal from research/EXPERIMENT_TEMPLATE.md. "
            "This command never authorizes execution, production, or BUY changes."
        )
    )
    parser.add_argument("experiment_id", help="Safe stable identifier (3-64 ASCII letters/digits/_/-).")
    parser.add_argument("--title", required=True, help="Short experiment title.")
    parser.add_argument("--owner", default="unassigned", help="Accountable researcher or team.")
    parser.add_argument("--hypothesis", default="", help="Falsifiable hypothesis for the proposal.")
    parser.add_argument("--notes", default="", help="Optional intake notes.")
    for name, weight in SCORE_WEIGHTS.items():
        parser.add_argument(
            "--" + name.replace("_", "-"),
            dest=name,
            type=int,
            required=True,
            metavar=f"0..{weight}",
            help=f"Score for {name} (maximum {weight}).",
        )
    parser.add_argument(
        "--root",
        type=Path,
        default=default_root(),
        help="Repository root (defaults to the root containing this script).",
    )
    parser.add_argument(
        "--template",
        type=Path,
        default=None,
        help="Template override; defaults to <root>/research/EXPERIMENT_TEMPLATE.md.",
    )
    parser.add_argument("--dry-run", action="store_true", help="Validate and print the proposal without writing files.")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    try:
        experiment_id = validate_experiment_id(args.experiment_id)
        scores = score_components(args)
    except ValueError as exc:
        parser.error(str(exc))

    title = args.title.strip()
    owner = args.owner.strip() or "unassigned"
    if not title:
        parser.error("--title must not be blank")

    root = args.root.resolve()
    research_dir = root / "research"
    template_path = args.template.resolve() if args.template is not None else research_dir / "EXPERIMENT_TEMPLATE.md"
    experiment_path = research_dir / "experiments" / f"{experiment_id}.md"
    queue_path = research_dir / "queue" / f"{experiment_id}.json"

    if not template_path.is_file():
        parser.error(f"experiment template not found: {template_path}")
    collisions = [path for path in (experiment_path, queue_path) if path.exists()]
    if collisions:
        parser.error("refusing to overwrite existing file(s): " + ", ".join(str(path) for path in collisions))

    created_at = utc_now()
    total = sum(scores.values())
    threshold_met = total >= RUN_SCORE_THRESHOLD
    status = "proposed" if threshold_met else "blocked_score"
    template = template_path.read_text(encoding="utf-8")
    markdown = render_markdown(
        template,
        experiment_id=experiment_id,
        title=title,
        owner=owner,
        hypothesis=args.hypothesis.strip(),
        notes=args.notes.strip(),
        created_at=created_at,
        status=status,
        scores=scores,
        total=total,
    )

    queue_payload: dict[str, Any] = {
        "schema_version": 1,
        "experiment_id": experiment_id,
        "title": title,
        "owner": owner,
        "hypothesis": args.hypothesis.strip(),
        "created_at": created_at,
        "status": status,
        "score": {
            "components": scores,
            "weights": SCORE_WEIGHTS,
            "total": total,
            "threshold": RUN_SCORE_THRESHOLD,
            "threshold_met": threshold_met,
        },
        "human_approved_to_run": False,
        "automatic_execution_allowed": False,
        "execution_authorized": False,
        "production_approved": False,
        "merge_approved": False,
        "buy_approved": False,
        "production_change_allowed": False,
        "merge_allowed": False,
        "buy_logic_change_allowed": False,
        "formal_buy": False,
        "send_order": False,
        "stake": 0,
        "experiment_markdown": relative_display(experiment_path, root),
        "notes": args.notes.strip(),
    }
    result = {
        "dry_run": bool(args.dry_run),
        "experiment_id": experiment_id,
        "status": status,
        "score_total": total,
        "score_threshold_met": threshold_met,
        "automatic_execution_allowed": False,
        "human_approval_required": True,
        "experiment_path": str(experiment_path),
        "queue_path": str(queue_path),
    }

    if args.dry_run:
        print(json.dumps({**result, "queue": queue_payload}, ensure_ascii=False, indent=2))
        return 0

    experiment_path.parent.mkdir(parents=True, exist_ok=True)
    queue_path.parent.mkdir(parents=True, exist_ok=True)
    wrote_experiment = False
    try:
        with experiment_path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(markdown)
        wrote_experiment = True
        with queue_path.open("x", encoding="utf-8", newline="\n") as handle:
            json.dump(queue_payload, handle, ensure_ascii=False, indent=2)
            handle.write("\n")
    except FileExistsError as exc:
        if wrote_experiment:
            experiment_path.unlink(missing_ok=True)
        parser.error(f"refusing to overwrite an experiment created concurrently: {exc.filename}")
    except OSError:
        if wrote_experiment and not queue_path.exists():
            experiment_path.unlink(missing_ok=True)
        raise

    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BrokenPipeError:
        sys.stderr.close()
        raise SystemExit(1)
