from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from scope_contract import (  # noqa: E402
    RUN_SCORE_THRESHOLD,
    SAFE_EXPERIMENT_ID,
    SCORE_WEIGHTS,
    canonical_digest,
    canonical_json_text,
    normalize_proposal_scope,
    proposal_score_total,
    strict_json_load,
)


def default_root() -> Path:
    return Path(__file__).resolve().parents[2]


def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def relative_display(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def render_markdown(
    template: str,
    *,
    scope: dict[str, Any],
    owner: str,
    notes: str,
    created_at: str,
    status: str,
    proposal_scope_digest: str,
    proposal_scope_path: str,
) -> str:
    scores = scope["score_components"]
    total = proposal_score_total(scope)
    replacements = {
        "{{EXPERIMENT_ID}}": scope["experiment_id"],
        "{{TITLE}}": scope["title"],
        "{{OWNER}}": owner,
        "{{HYPOTHESIS}}": scope["hypothesis"],
        "{{NULL_HYPOTHESIS}}": scope["null_hypothesis"],
        "{{RACING_MECHANISM}}": scope["racing_mechanism"],
        "{{CREATED_AT}}": created_at,
        "{{STATUS}}": status,
        "{{BASE_COMMIT}}": scope["base_commit"],
        "{{DATA_AS_OF}}": scope["data_as_of"],
        "{{PROPOSAL_SCOPE_DIGEST}}": proposal_scope_digest,
        "{{PROPOSAL_SCOPE_PATH}}": proposal_scope_path,
        "{{SCORE_INDEPENDENT_INFORMATION}}": str(scores["independent_information"]),
        "{{SCORE_RACING_MECHANISM}}": str(scores["racing_mechanism"]),
        "{{SCORE_OUTER_OOS_FAILURE_EVIDENCE}}": str(
            scores["outer_oos_failure_evidence"]
        ),
        "{{SCORE_LEAKAGE_SAFETY}}": str(scores["leakage_safety"]),
        "{{SCORE_MINIMAL_FALSIFIABILITY}}": str(scores["minimal_falsifiability"]),
        "{{SCORE_ACQUISITION_IMPLEMENTATION_COST}}": str(
            scores["acquisition_implementation_cost"]
        ),
        "{{SCORE_TOTAL}}": str(total),
        "{{AUTO_EXECUTION_ELIGIBLE}}": "false",
    }
    rendered = template
    for marker, value in replacements.items():
        rendered = rendered.replace(marker, str(value))

    score_rows = "\n".join(
        f"| `{name}` | {scores[name]} | {weight} |"
        for name, weight in SCORE_WEIGHTS.items()
    )
    intake = f"""<!--
Generated by scripts/research/create_experiment.py.
The canonical JSON file, not this Markdown, is the approval scope source.
-->

# {scope["experiment_id"]}: {scope["title"]}

## Level-3 intake

- Status: `{status}`
- Owner: {owner}
- Created at (UTC): `{created_at}`
- Score: **{total}/100** (run threshold: {RUN_SCORE_THRESHOLD})
- Proposal scope: `{proposal_scope_path}`
- Proposal scope digest: `{proposal_scope_digest}`
- Automatic execution: **forbidden**
- APPROVED_TO_PREPARE: **not granted**
- APPROVED_TO_RUN: **not granted**
- Production / merge / BUY approval: **false**
- Formal BUY: **false**
- Send order: **false**
- Stake: **0**

### Canonical proposal

The canonical JSON is serialized as UTF-8 with sorted object keys, compact
separators, preserved Unicode, and no NaN/Infinity.  Set-like proposal arrays
are sorted and unique; command arrays preserve order.

### Intake scorecard

| Dimension | Score | Maximum |
|---|---:|---:|
{score_rows}

### Intake notes

{notes or "なし"}

---

"""
    return intake + rendered.rstrip() + "\n"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Create a Level-3 research proposal from canonical JSON. "
            "This command never authorizes preparation, real-data execution, "
            "production, merge, or BUY changes."
        )
    )
    parser.add_argument("experiment_id", help="Safe stable identifier.")
    parser.add_argument(
        "--proposal-scope",
        type=Path,
        required=True,
        help="Strict JSON containing the complete canonical proposal scope.",
    )
    parser.add_argument("--owner", default="unassigned", help="Accountable researcher or team.")
    parser.add_argument("--notes", default="", help="Optional intake notes outside approval scope.")
    parser.add_argument("--root", type=Path, default=default_root(), help="Repository root.")
    parser.add_argument(
        "--template",
        type=Path,
        default=None,
        help="Template override; defaults to <root>/research/EXPERIMENT_TEMPLATE.md.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate and print without writing proposal files.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    experiment_id = args.experiment_id.strip()
    if not SAFE_EXPERIMENT_ID.fullmatch(experiment_id):
        parser.error("experiment_id is not a safe 3-64 character identifier")

    input_scope_path = args.proposal_scope.resolve()
    try:
        scope = normalize_proposal_scope(
            strict_json_load(input_scope_path),
            expected_experiment_id=experiment_id,
        )
    except ValueError as exc:
        parser.error(str(exc))

    root = args.root.resolve()
    research_dir = root / "research"
    template_path = (
        args.template.resolve()
        if args.template is not None
        else research_dir / "EXPERIMENT_TEMPLATE.md"
    )
    experiment_path = research_dir / "experiments" / f"{experiment_id}.md"
    queue_path = research_dir / "queue" / f"{experiment_id}.json"
    scope_path = research_dir / "scopes" / f"{experiment_id}.proposal.json"
    if not template_path.is_file():
        parser.error(f"experiment template not found: {template_path}")
    collisions = [
        path for path in (experiment_path, queue_path, scope_path) if path.exists()
    ]
    if collisions:
        parser.error(
            "refusing to overwrite existing file(s): "
            + ", ".join(str(path) for path in collisions)
        )

    created_at = utc_now()
    total = proposal_score_total(scope)
    threshold_met = total >= RUN_SCORE_THRESHOLD
    status = "proposed" if threshold_met else "blocked_score"
    proposal_scope_digest = canonical_digest(scope)
    proposal_scope_file = relative_display(scope_path, root)
    markdown = render_markdown(
        template_path.read_text(encoding="utf-8"),
        scope=scope,
        owner=args.owner.strip() or "unassigned",
        notes=args.notes.strip(),
        created_at=created_at,
        status=status,
        proposal_scope_digest=proposal_scope_digest,
        proposal_scope_path=proposal_scope_file,
    )

    queue_payload: dict[str, Any] = {
        "schema_version": 2,
        "experiment_id": experiment_id,
        "title": scope["title"],
        "owner": args.owner.strip() or "unassigned",
        "created_at": created_at,
        "status": status,
        "score": {
            "components": scope["score_components"],
            "weights": SCORE_WEIGHTS,
            "total": total,
            "threshold": RUN_SCORE_THRESHOLD,
            "threshold_met": threshold_met,
        },
        "proposal_scope": scope,
        "proposal_scope_file": proposal_scope_file,
        "proposal_scope_digest": proposal_scope_digest,
        "human_approved_to_prepare": False,
        "human_approved_to_run": False,
        "human_approved_for_shadow": False,
        "automatic_execution_allowed": False,
        "execution_authorized": False,
        "production_approved": False,
        "merge_approved": False,
        "buy_approved": False,
        "production_change_allowed": False,
        "merge_allowed": False,
        "buy_logic_change_allowed": False,
        "formal_buy": False,
        "send_order": False,
        "stake": 0,
        "experiment_markdown": relative_display(experiment_path, root),
        "notes": args.notes.strip(),
    }
    result = {
        "dry_run": bool(args.dry_run),
        "experiment_id": experiment_id,
        "status": status,
        "score_total": total,
        "score_threshold_met": threshold_met,
        "proposal_scope_digest": proposal_scope_digest,
        "automatic_execution_allowed": False,
        "human_approval_required": True,
        "experiment_path": str(experiment_path),
        "queue_path": str(queue_path),
        "proposal_scope_path": str(scope_path),
    }
    if args.dry_run:
        print(json.dumps({**result, "queue": queue_payload}, ensure_ascii=False, indent=2))
        return 0

    for path in (experiment_path.parent, queue_path.parent, scope_path.parent):
        path.mkdir(parents=True, exist_ok=True)
    created: list[Path] = []
    try:
        with scope_path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(canonical_json_text(scope) + "\n")
        created.append(scope_path)
        with experiment_path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(markdown)
        created.append(experiment_path)
        with queue_path.open("x", encoding="utf-8", newline="\n") as handle:
            json.dump(queue_payload, handle, ensure_ascii=False, indent=2, allow_nan=False)
            handle.write("\n")
        created.append(queue_path)
    except (FileExistsError, OSError):
        for path in reversed(created):
            path.unlink(missing_ok=True)
        raise

    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BrokenPipeError:
        sys.stderr.close()
        raise SystemExit(1)
